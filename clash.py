def encode_tag(tag: str) -> str:
    """
    Encode a Clash of Clans tag for use in URL paths.
    Replaces '#' with '%23' as required by the API.

    Args:
        tag: Raw clan/player tag (with or without #).

    Returns:
        str: URL-encoded tag string.
    """
    tag = tag.strip()

    # Accept already-url-encoded tags too: "%23ABC" -> "#ABC"
    if tag.lower().startswith("%23"):
        tag = "#" + tag[3:]

    if not tag.startswith("#"):
        tag = "#" + tag
    return quote(tag, safe="")


def clash_get(endpoint: str, retry_on_auth: bool = True) -> dict | None:
    """
    Perform a GET request to the Clash of Clans API.
    Automatically injects the current bearer token.
    Handles token refresh on 401/403 responses.

    Args:
        endpoint: API endpoint path (e.g. '/clans/%23TAG').
        retry_on_auth: Whether to retry with a fresh token on auth errors.

    Returns:
        dict | None: Parsed JSON response, or None on failure.
    """
    global _clash_token

    if not _clash_token:
        get_clash_token()

    url = f"{COC_API_BASE}{endpoint}"
    headers = {
        "Authorization": f"Bearer {_clash_token}",
        "Accept": "application/json",
    }

    try:
        logger.info("GET %s", url)
        response = requests.get(url, headers=headers, timeout=REQUEST_TIMEOUT)

        # Handle authentication errors with token refresh
        if response.status_code in (401, 403):
            if retry_on_auth:
                logger.warning(
                    "Auth error %d on %s. Refreshing token...",
                    response.status_code,
                    endpoint,
                )
                refresh_token()
                return clash_get(endpoint, retry_on_auth=False)
            else:
                logger.error(
                    "Auth error %d persists after token refresh: %s",
                    response.status_code,
                    endpoint,
                )
                return None

        # Handle rate limiting
        if response.status_code == 429:
            logger.warning("Rate limited by Clash of Clans API. Endpoint: %s", endpoint)
            return {"_error": "rate_limit"}

        # Maintenance / service unavailable
        if response.status_code == 503:
            try:
                payload = response.json()
            except Exception:
                payload = {}
            reason = str(payload.get("reason", "") or "")
            if reason == "inMaintenance":
                logger.warning("Clash API maintenance mode (503). Endpoint: %s", endpoint)
                return {"_error": "maintenance"}
            logger.warning("Clash API service unavailable (503). Endpoint: %s", endpoint)
            return {"_error": "service_unavailable"}

        # Handle not found
        if response.status_code == 404:
            logger.info("Resource not found: %s", endpoint)
            return {"_error": "not_found"}

        # Handle other errors
        if response.status_code != 200:
            logger.error(
                "API returned status %d for endpoint: %s | Body: %s",
                response.status_code,
                endpoint,
                response.text[:200],
            )
            return None

        return response.json()

    except requests.exceptions.Timeout:
        logger.error("Request timed out for endpoint: %s", endpoint)
        return {"_error": "timeout"}

    except requests.exceptions.ConnectionError as exc:
        logger.error("Connection error for endpoint %s: %s", endpoint, exc)
        return {"_error": "connection"}

    except requests.exceptions.RequestException as exc:
        logger.error("Request exception for endpoint %s: %s", endpoint, exc)
        return None

    except Exception as exc:
        logger.error("Unexpected error during GET %s: %s", endpoint, exc)
        return None


