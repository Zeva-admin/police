def _format_time_utc(iso_str: str | None) -> str:
    if not iso_str:
        return "—"
    raw = str(iso_str).strip()
    dt = _parse_coc_time(raw)

    if not dt:
        s = raw
        s = s.replace("T", " ").replace(".000Z", "").replace("Z", "").strip()
        if s.upper().endswith("UTC"):
            s = s[:-3].strip()
        for fmt in ("%Y%m%d %H%M%S", "%Y-%m-%d %H:%M:%S"):
            try:
                dt = datetime.strptime(s, fmt).replace(tzinfo=timezone.utc)
                break
            except ValueError:
                continue
        if not dt:
            digits = "".join(ch for ch in s if ch.isdigit())
            if len(digits) >= 14:
                try:
                    dt = datetime.strptime(digits[:14], "%Y%m%d%H%M%S").replace(tzinfo=timezone.utc)
                except ValueError:
                    dt = None

    if not dt:
        return raw

    local = dt.astimezone(LOCAL_TZ)
    local_s = local.strftime("%d.%m.%Y %H:%M")
    sign = "+" if LOCAL_UTC_OFFSET_HOURS >= 0 else "−"
    off = abs(int(LOCAL_UTC_OFFSET_HOURS))
    return f"{local_s} (UTC{sign}{off})"


def _parse_coc_time(ts: str | None) -> datetime | None:
    if not ts:
        return None
    s = str(ts).strip()
    for fmt in ("%Y%m%dT%H%M%S.000Z", "%Y-%m-%dT%H:%M:%S.000Z"):
        try:
            return datetime.strptime(s, fmt).replace(tzinfo=timezone.utc)
        except ValueError:
            continue
    return None


def _time_left(end_ts: str | None) -> str:
    end_dt = _parse_coc_time(end_ts)
    if not end_dt:
        return "—"
    now = datetime.now(timezone.utc)
    delta = end_dt - now
    seconds = int(delta.total_seconds())
    if seconds <= 0:
        return "0м"
    minutes = seconds // 60
    hours = minutes // 60
    days = hours // 24
    minutes = minutes % 60
    hours = hours % 24
    parts: list[str] = []
    if days:
        parts.append(f"{days}д")
    if hours:
        parts.append(f"{hours}ч")
    parts.append(f"{minutes}м")
    return " ".join(parts)


def _time_until(ts: str | None) -> str:
    dt = _parse_coc_time(ts)
    if not dt:
        return "—"
    now = datetime.now(timezone.utc)
