def _validate_webapp_init_data(init_data: str) -> dict | None:
    """
    Validate Telegram WebApp initData and return parsed user dict.
    Returns None if invalid/expired.
    """
    if not init_data or not isinstance(init_data, str):
        return None
    try:
        data = urllib.parse.parse_qs(init_data, strict_parsing=True)
    except Exception:
        return None
    if "hash" not in data:
        return None
    recv_hash = (data.get("hash") or [""])[0]
    pairs = []
    for k in sorted(data.keys()):
        if k == "hash":
            continue
        v = (data.get(k) or [""])[0]
        pairs.append(f"{k}={v}")
    data_check_string = "\n".join(pairs)
    # Telegram WebApp initData signature:
    # secret_key = HMAC_SHA256("WebAppData", bot_token)
    # hash = HMAC_SHA256(data_check_string, secret_key)
    secret_key = hmac.new(
        b"WebAppData",
        TELEGRAM_BOT_TOKEN.encode("utf-8"),
        hashlib.sha256,
    ).digest()
    calc_hash = hmac.new(
        secret_key,
        data_check_string.encode("utf-8"),
        hashlib.sha256,
    ).hexdigest()
    if not hmac.compare_digest(calc_hash, str(recv_hash).strip().lower()):
        return None
    try:
        auth_date = int((data.get("auth_date") or ["0"])[0])
    except Exception:
        auth_date = 0
    if auth_date and (time.time() - auth_date) > 24 * 3600:
        return None
    user_raw = (data.get("user") or [""])[0]
    try:
        user = json.loads(user_raw) if user_raw else None
    except Exception:
        user = None
    if not isinstance(user, dict) or "id" not in user:
        return None
    return user


