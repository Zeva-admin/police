def build_war_text(data: dict, *, mode: str = "war", include_title: bool = True) -> str:
    state = str(data.get("state", "notInWar"))
    team_size = data.get("teamSize", "—")
    default_apm = 1 if mode == "cwl" else 2
    attacks_per_member = int(data.get("attacksPerMember", default_apm) or default_apm)
    if mode == "cwl":
        # В ЛВК всегда 1 атака на участника за день войны
        attacks_per_member = 1

    our = data.get("clan", {}) or {}
    opp = data.get("opponent", {}) or {}

    our_name = _safe(our.get("name", "Мы"))
    opp_name = _safe(opp.get("name", "Соперник"))

    our_stars = int(our.get("stars", 0) or 0)
    opp_stars = int(opp.get("stars", 0) or 0)
    our_destr = float(our.get("destructionPercentage", 0.0) or 0.0)
    opp_destr = float(opp.get("destructionPercentage", 0.0) or 0.0)
    our_attacks = int(our.get("attacks", 0) or 0)
    opp_attacks = int(opp.get("attacks", 0) or 0)

    total_attacks = (
        int(team_size) * attacks_per_member if str(team_size).isdigit() else None
    )
    our_left = (total_attacks - our_attacks) if isinstance(total_attacks, int) else None
    opp_left = (total_attacks - opp_attacks) if isinstance(total_attacks, int) else None

    prep = _format_time_utc(data.get("preparationStartTime"))
    start = _format_time_utc(data.get("startTime"))
    end = _format_time_utc(data.get("endTime"))
    left = _time_left(data.get("endTime"))

    if state == "notInWar":
        return "😴 Сейчас войны нет."

    our_members = our.get("members", []) or []
    opp_members = opp.get("members", []) or []
    our_by_tag = {m.get("tag"): m for m in our_members if isinstance(m, dict)}
    opp_by_tag = {m.get("tag"): m for m in opp_members if isinstance(m, dict)}

    missing: list[str] = []
    for m in our_members:
        if not isinstance(m, dict):
            continue
        raw_name = str(m.get("name", "—") or "—")
        th = m.get("townhallLevel", "?")
        used = len(m.get("attacks", []) or [])
        if used < attacks_per_member:
            name_html = _maybe_mention_player(raw_name, m.get("tag"))
            missing.append(f"{name_html} (TH{th}) — {used}/{attacks_per_member}")

    opp_missing_count = 0
    for m in opp_members:
        if not isinstance(m, dict):
            continue
        used = len(m.get("attacks", []) or [])
        if used < attacks_per_member:
            opp_missing_count += 1

    attacks_flat: list[dict] = []
    for m in our_members:
        for a in (m.get("attacks") or []):
            if isinstance(a, dict):
                attacks_flat.append(a)
    attacks_flat.sort(key=lambda a: a.get("order", 10**9))

    # Render attack list:
    # - for small wars (<=20) show all attacks
    # - for large wars show the latest 25 (keeps message within Telegram limits)
    attack_limit = 25
    if str(team_size).isdigit() and int(team_size) <= 20:
        attack_limit = 200  # effectively "all"
    attacks_slice = attacks_flat[-attack_limit:]

    last_attacks_lines: list[str] = []
    for a in attacks_slice:
        attacker = our_by_tag.get(a.get("attackerTag")) or {}
        defender = opp_by_tag.get(a.get("defenderTag")) or {}
        attacker_raw = str(attacker.get("name") or a.get("attackerTag") or "—")
        attacker_name = _maybe_mention_player(attacker_raw, attacker.get("tag"))
        defender_name = _safe(defender.get("name", a.get("defenderTag", "—")))
        dpos = defender.get("mapPosition", "?")
        stars = int(a.get("stars", 0) or 0)
        destr = int(a.get("destructionPercentage", 0) or 0)
        stars_str = "⭐" * stars + "☆" * (3 - stars)
        last_attacks_lines.append(
            f"{attacker_name} → #{dpos} <b>{defender_name}</b> — {stars_str} — <b>{destr}%</b>"
        )

    if missing:
        label = "❌ <b>Кто не атаковал:</b>" if state == "warEnded" else "❌ <b>Кому ещё нужно атаковать:</b>"
        missing_block = "\n\n" + label + "\n" + "\n".join(
            f"{i}. {line}" for i, line in enumerate(missing, start=1)
        )
    else:
        missing_block = "\n\n✅ <b>По нашим — все атаки сделаны.</b>"
    last_attacks_block = ""
    if last_attacks_lines:
        last_attacks_block = "\n\n🧾 <b>Последние атаки:</b>\n" + "\n".join(
            f"{i}. {line}" for i, line in enumerate(last_attacks_lines, start=1)
        )

    left_line = ""
    if our_left is not None and opp_left is not None:
        left_line = (
            f"\nАтаки: <b>{our_attacks}/{total_attacks}</b> (осталось {our_left})"
            f" • Соперник <b>{opp_attacks}/{total_attacks}</b> (осталось {opp_left})"
        )

    time_block = f"⏳ Осталось: <b>{_safe(left)}</b>\n\n"
    if state == "warEnded":
        time_block = "\n\n"

    body = (
        f"Тег клана: <code>{_safe(CLAN_TAG)}</code>\n"
        f"Статус: <b>{_safe(_normalize_state_label(state))}</b>\n"
        f"Формат: <b>{team_size}×{team_size}</b> • атак на участника: <b>{attacks_per_member}</b>\n"
        f"🏁 Конец: <b>{_safe(end)}</b>\n"
        f"{time_block}"
        f"🏰 <b>{our_name}</b>: ⭐ <b>{our_stars}</b> • 💥 <b>{our_destr:.2f}%</b>\n"
        f"🟥 <b>{opp_name}</b>: ⭐ <b>{opp_stars}</b> • 💥 <b>{opp_destr:.2f}%</b>"
        f"{left_line}"
        f"\nБез атак: мы <b>{len(missing)}</b> • соперник <b>{opp_missing_count}</b>"
        f"{missing_block}"
        f"{last_attacks_block}"
    )
    if not include_title:
        return body
    title = (
        "🏅 <b>ЛВК — Война</b>\n━━━━━━━━━━━━━━━━━━━━\n\n"
        if mode == "cwl"
        else "⚔️ <b>Война</b>\n\n"
    )
    return title + body


