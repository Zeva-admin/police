def _norm_tag(tag: str | None) -> str:
    if not tag:
        return ""
    t = str(tag).strip()
    if t.lower().startswith("%23"):
        t = "#" + t[3:]
    if not t.startswith("#"):
        t = "#" + t
    return t.upper()


