def validate_tag(tag: str) -> bool:
    """
    Basic validation of a Clash of Clans tag.

    Args:
        tag: Raw tag string from user input.

    Returns:
        bool: True if tag appears valid, False otherwise.
    """
    raw = tag.strip()
    if raw.lower().startswith("%23"):
        raw = "#" + raw[3:]
    cleaned = raw.lstrip("#").upper()
    allowed_chars = set("0289PYLQGRJCUV")
    return 3 <= len(cleaned) <= 12 and all(c in allowed_chars for c in cleaned)


