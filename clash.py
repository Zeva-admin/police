def search_members(members: list[dict], query: str) -> list[dict]:
    q = (query or "").strip().lower()
    if not q:
        return []
    res: list[dict] = []
    for m in members:
        if not isinstance(m, dict):
            continue
        name = str(m.get("name", "")).lower()
        tag = str(m.get("tag", "")).lower()
        if q in name or q in tag:
            res.append(m)
    return res


