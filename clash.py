def _decode_jwt_payload(jwt_token: str) -> dict:
    """
    Decode the payload part of a JWT without verifying signature.
    Used only to extract the current IP provided by the CoC developer portal login.
    """
    parts = jwt_token.split(".")
    if len(parts) < 2:
        raise ValueError("Invalid JWT format (expected 3 parts).")

    payload_b64 = parts[1]
    padding = "=" * (-len(payload_b64) % 4)
    payload_bytes = base64.urlsafe_b64decode(payload_b64 + padding)
    payload = json.loads(payload_bytes.decode("utf-8"))
    if not isinstance(payload, dict):
        raise ValueError("JWT payload is not a JSON object.")
    return payload


def _extract_ip_from_login_token(temporary_api_token: str) -> str:
    """
    Extract current public IP address from the developer portal temporary API token.
    """
    payload = _decode_jwt_payload(temporary_api_token)

    limits = payload.get("limits", [])
    if isinstance(limits, list):
        for limit in limits:
            if not isinstance(limit, dict):
                continue
            cidrs = limit.get("cidrs", [])
            if not isinstance(cidrs, list):
                continue
            for cidr in cidrs:
                if isinstance(cidr, str) and "/" in cidr:
                    ip = cidr.split("/", 1)[0].strip()
                    if ip:
                        return ip

    raise ValueError("Could not extract current IP from temporaryAPIToken payload.")


def _devportal_get_or_create_token() -> str:
    """
    Login to the CoC developer portal and ensure a key exists for the current IP.

    This replaces the unofficial `clashapi` behavior and fixes a common failure mode:
    when the account has zero keys, some wrappers return an empty list instead of creating one.
    """
    session = requests.Session()

    login = session.post(
        url=f"{DEVPORTAL_BASE}/api/login",
        json={"email": CLASH_EMAIL, "password": CLASH_PASSWORD},
        timeout=REQUEST_TIMEOUT,
    )
    if not login.ok:
        raise RuntimeError(f"Developer portal login failed (HTTP {login.status_code}).")

    login_json = login.json()
    temporary_token = login_json.get("temporaryAPIToken")
    if not isinstance(temporary_token, str) or not temporary_token:
        raise RuntimeError("Developer portal login did not return temporaryAPIToken.")

    current_ip = _extract_ip_from_login_token(temporary_token)

    keys_resp = session.post(
        url=f"{DEVPORTAL_BASE}/api/apikey/list",
        json={},
        timeout=REQUEST_TIMEOUT,
    )
    keys_json = keys_resp.json() if keys_resp.ok else {}
    keys = keys_json.get("keys", [])
    if not isinstance(keys, list):
        keys = []

    # Prefer an existing key already matching our current IP.
    for key in keys:
        if not isinstance(key, dict):
            continue
        cidr_ranges = key.get("cidrRanges", [])
        if (
            isinstance(cidr_ranges, list)
            and any(
                isinstance(cidr, str) and cidr.split("/", 1)[0] == current_ip
                for cidr in cidr_ranges
            )
            and isinstance(key.get("key"), str)
            and key.get("key")
        ):
            return key["key"]

    # No matching key found: create a new one for this IP.
    created = session.post(
        url=f"{DEVPORTAL_BASE}/api/apikey/create",
        json={
            "cidrRanges": [current_ip],
            "description": DEVPORTAL_KEY_DESCRIPTION,
            "name": DEVPORTAL_KEY_NAME,
            "scopes": [DEVPORTAL_SCOPE],
        },
        timeout=REQUEST_TIMEOUT,
    )
    if not created.ok:
        raise RuntimeError(f"Failed to create developer portal key (HTTP {created.status_code}).")

    # Re-list and pick the newly created key for this IP.
    keys_resp = session.post(
        url=f"{DEVPORTAL_BASE}/api/apikey/list",
        json={},
        timeout=REQUEST_TIMEOUT,
    )
    keys_json = keys_resp.json() if keys_resp.ok else {}
    keys = keys_json.get("keys", [])
    if not isinstance(keys, list):
        keys = []

    for key in keys:
        if not isinstance(key, dict):
            continue
        cidr_ranges = key.get("cidrRanges", [])
        if (
            isinstance(cidr_ranges, list)
            and any(
                isinstance(cidr, str) and cidr.split("/", 1)[0] == current_ip
                for cidr in cidr_ranges
            )
            and isinstance(key.get("key"), str)
            and key.get("key")
        ):
            return key["key"]

    raise RuntimeError("Developer portal key creation succeeded, but no key could be read back.")


def get_clash_token() -> str:
    """
    Retrieve a Clash of Clans API token.

    Uses `clashapi` (required) to keep keys updated for dynamic IP.
    If the developer account has no keys yet and `clashapi` returns an empty list,
    we create a key via the developer portal once, then `clashapi` can manage it.
    Retries up to TOKEN_RETRY_ATTEMPTS times on failure.

    Returns:
        str: A valid API bearer token.

    Raises:
        SystemExit: If all retry attempts are exhausted.
    """
    global _clash_token, _clash_token_source

    if clashapi is None:
        logger.critical(
            "`clashapi` is required but could not be imported. Install it or fix your environment."
        )
        sys.exit(1)

    for attempt in range(1, TOKEN_RETRY_ATTEMPTS + 1):
        try:
            logger.info(
                "Attempting to fetch Clash of Clans API token "
                "(attempt %d/%d)...",
                attempt,
                TOKEN_RETRY_ATTEMPTS,
            )

            # 1) Try clashapi first (updates keys if IP changes)
            tokens = clashapi.coc(CLASH_EMAIL, CLASH_PASSWORD)
            if isinstance(tokens, (list, tuple)) and tokens and isinstance(tokens[0], str) and tokens[0]:
                token = tokens[0]
            else:
                # 2) If there are no keys yet, create one once via portal and retry clashapi
                logger.warning(
                    "clashapi returned no keys. Creating a developer portal key for this IP once..."
                )
                _devportal_get_or_create_token()
                tokens = clashapi.coc(CLASH_EMAIL, CLASH_PASSWORD)
                if not isinstance(tokens, (list, tuple)) or not tokens or not isinstance(tokens[0], str) or not tokens[0]:
                    raise ValueError(f"clashapi returned an unexpected response: {tokens!r}")
                token = tokens[0]

            _clash_token = token
            _clash_token_source = "clashapi"
            logger.info("Successfully retrieved Clash of Clans API token.")
            return _clash_token

        except Exception as exc:
            logger.error(
                "Failed to retrieve token on attempt %d/%d: %s",
                attempt,
                TOKEN_RETRY_ATTEMPTS,
                exc,
            )

            if attempt < TOKEN_RETRY_ATTEMPTS:
                logger.warning(
                    "Retrying in %d seconds...", TOKEN_RETRY_DELAY
                )
                time.sleep(TOKEN_RETRY_DELAY)
            else:
                logger.critical(
                    "All %d token retrieval attempts exhausted. "
                    "Cannot start the bot. "
                    "Fix: check developer portal credentials and make sure the account can create API keys.",
                    TOKEN_RETRY_ATTEMPTS,
                )
                sys.exit(1)

    # This line is unreachable but satisfies type checkers
    sys.exit(1)


def refresh_token() -> str:
    """
    Force-refresh the Clash of Clans API token.
    Called automatically when a 403 or 401 response is detected.

    Returns:
        str: A new valid API bearer token.
    """
    logger.warning("Token expired or unauthorized. Refreshing token...")
    return get_clash_token()


