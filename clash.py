async def main() -> None:
    """
    Main entry point for the bot.
    1. Validates environment configuration.
    2. Retrieves the Clash of Clans API token.
    3. Starts the aiogram polling loop.
    """

    # Validate Telegram token
    if not TELEGRAM_BOT_TOKEN:
        logger.critical(
            "TELEGRAM_BOT_TOKEN не задан. Завершение."
        )
        sys.exit(1)

    if CLASH_EMAIL == "your_email@example.com" or CLASH_PASSWORD == "your_password":
        logger.warning(
            "Похоже, у тебя стоят дефолтные учётные данные Clash. "
            "Проверь CLASH_EMAIL и CLASH_PASSWORD в clash.py."
        )

    if CLAN_TAG.strip().upper() in {"#YOUR_CLAN_TAG", "YOUR_CLAN_TAG", "#CLAN_TAG"}:
        logger.warning(
            "CLAN_TAG похож на плейсхолдер. Укажи тег клана в clash.py (CLAN_TAG = '#...')."
        )

    # Retrieve initial API token
    logger.info("Initializing Clash of Clans API token...")
    get_clash_token()
    logger.info("Клан по умолчанию: %s", CLAN_TAG)
    try:
        clan = get_clan_info(CLAN_TAG)
        if isinstance(clan, dict) and not clan.get("_error"):
            cname = str(clan.get("name") or "").strip()
            global _CLAN_NAME_CACHED
            if cname:
                _CLAN_NAME_CACHED = cname
    except Exception:
        pass

    # Initialize bot instance early (used by WebApp verification handler for announcements)
    bot = Bot(token=TELEGRAM_BOT_TOKEN)
    global _BOT_INSTANCE
    _BOT_INSTANCE = bot
    dp = router_dp

    # Render web server (binds to $PORT): health-check + Telegram Mini App.
    server_runner = await start_render_server()

    # Show public URL in logs (useful to paste into BotFather / UI)
    try:
        public_url = (os.environ.get("RENDER_EXTERNAL_URL") or "").strip().rstrip("/")
        if not public_url:
            public_url = (PUBLIC_BASE_URL or "").strip().rstrip("/")
        logger.info("Web URL: %s", public_url or "—")
        if public_url:
            logger.info("Mini App URL: %s/webapp", public_url)
    except Exception:
        pass

    # Prepare DB for Mini App links (Supabase)
    try:
        await _pg_ensure_schema()
        await _refresh_links_cache(force=True)
        await _refresh_tg_links_cache(force=True)
        logger.info("Supabase: connected")
    except Exception as exc:
        logger.warning("Supabase: not connected (%s)", exc)

    # Auto notifications for clan chat (new messages, milestone-based)
    try:
        if isinstance(CHAT_ID, int) and CHAT_ID != 0:
            if CHAT_ID not in _broadcast_tasks or _broadcast_tasks[CHAT_ID].done():
                # Verify that bot can access the chat (avoid noisy "chat not found" loops)
                try:
                    await bot.get_chat(CHAT_ID)
                    _broadcast_tasks[CHAT_ID] = asyncio.create_task(
                        _broadcast_milestones_loop(bot, CHAT_ID)
                    )
                    logger.info("Auto broadcast notifications enabled for chat %s", CHAT_ID)
                except Exception as exc:
                    logger.warning("Auto broadcast disabled: cannot access chat %s (%s)", CHAT_ID, exc)
    except Exception:
        pass

    def _shutdown() -> None:
        if not SHUTDOWN_EVENT.is_set():
            SHUTDOWN_EVENT.set()
            logger.info("Получен сигнал завершения. Останавливаю бота...")

    try:
        loop = asyncio.get_running_loop()
        try:
            loop.add_signal_handler(signal.SIGTERM, _shutdown)
            loop.add_signal_handler(signal.SIGINT, _shutdown)
        except Exception:
            # Signal handlers may be unsupported on Windows
            pass

        # Ensure no webhook is set (polling only)
        try:
            await bot.delete_webhook(drop_pending_updates=True)
        except Exception:
            pass

        logger.info("Starting Clash of Clans Telegram bot in polling mode (Render-ready)...")
        logger.info("Bot is ready. Listening for messages...")

        while not SHUTDOWN_EVENT.is_set():
            try:
                await dp.start_polling(
                    bot,
                    allowed_updates=["message", "callback_query"],
                    drop_pending_updates=True,
                )
                if not SHUTDOWN_EVENT.is_set():
                    logger.warning("Polling завершился. Перезапуск через 3 секунды...")
                    await asyncio.sleep(3)
            except Exception as exc:
                if SHUTDOWN_EVENT.is_set():
                    break
                logger.error("Ошибка polling: %s. Перезапуск через 5 секунд...", exc)
                await asyncio.sleep(5)
    finally:
        SHUTDOWN_EVENT.set()
        for chat_id, task in list(_notify_tasks.items()):
            try:
                task.cancel()
            except Exception:
                pass
        _notify_tasks.clear()
        for chat_id, task in list(_broadcast_tasks.items()):
            try:
                task.cancel()
            except Exception:
                pass
        _broadcast_tasks.clear()

        try:
            await server_runner.cleanup()
        except Exception:
            pass
        await bot.session.close()
        logger.info("Bot session closed.")


if __name__ == "__main__":
    try:
        asyncio.run(main())
    except KeyboardInterrupt:
        logger.info("Bot stopped by user (KeyboardInterrupt).")
    except SystemExit as exc:
        logger.info("Bot exited with code: %s", exc.code)
        sys.exit(exc.code)
