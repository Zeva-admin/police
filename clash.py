def extract_tag_arg(text: str, default_tag: str | None = None) -> str | None:
    """
    Extract a single tag argument from a command text.

    Supports tags like "#ABC" or "%23ABC". Returns:
    - default_tag if no argument provided
    - None if an argument is provided but invalid
    """
    parts = (text or "").split(maxsplit=1)
    if len(parts) < 2:
        return default_tag

    tag = parts[1].strip().split()[0]
    if not validate_tag(tag):
        return None
    return tag


