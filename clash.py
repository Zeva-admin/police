def find_our_war_in_round(round_data: dict, clan_tag: str) -> tuple[str | None, dict | None]:
    tags = round_data.get("warTags", []) if isinstance(round_data, dict) else []
    for wt in tags:
        if not isinstance(wt, str) or wt == "#0":
            continue
        war = get_cwl_war(wt)
        if not isinstance(war, dict) or war.get("_error"):
            continue
        ctag = _norm_tag((war.get("clan") or {}).get("tag"))
        otag = _norm_tag((war.get("opponent") or {}).get("tag"))
        if ctag == clan_tag or otag == clan_tag:
            return wt, war
    return None, None


def get_current_cwl_war_for_clan() -> tuple[str | None, dict | None]:
    """
    Try to find an active CWL war for our clan.
    Returns (war_tag, war_data) or (None, None).
    """
    group = get_cwl_group()
    if not isinstance(group, dict) or group.get("_error"):
        return None, None

    rounds = group.get("rounds", []) or []
    our_tag = _norm_tag(CLAN_TAG)
    for r in rounds:
        if not isinstance(r, dict):
            continue
        tags = r.get("warTags", []) or []
        for wt in tags:
            if not isinstance(wt, str) or wt == "#0":
                continue
            war = get_cwl_war(wt)
            if not isinstance(war, dict):
                continue
            state = str(war.get("state", ""))
            if state not in {"preparation", "inWar"}:
                continue
            ctag = _norm_tag((war.get("clan") or {}).get("tag"))
            otag = _norm_tag((war.get("opponent") or {}).get("tag"))
            if ctag == our_tag or otag == our_tag:
                return wt, war

    # fallback: just return any war involving us
    for r in rounds:
        war_tag, war = find_our_war_in_round(r, _norm_tag(CLAN_TAG))
        if war_tag and isinstance(war, dict):
            return war_tag, war

    return None, None


def get_war_missing_attacks(war: dict, clan_tag: str) -> tuple[str, list[str], str, str]:
    """
    Returns:
      title: "КВ" or "ЛВК"
      missing_lines: list of formatted lines with players missing attacks
      state: war state
      end_time: endTime string (API format)
    """
    state = str(war.get("state", "notInWar"))
    # For preparation we count down to the battle start, for inWar — to the battle end.
    deadline = war.get("endTime") if state == "inWar" else war.get("startTime")
    end_time = str(deadline or "")

    attacks_per_member = int(war.get("attacksPerMember", 2) or 2)
    clan = war.get("clan", {}) or {}
    opp = war.get("opponent", {}) or {}

    our_tag = _norm_tag(clan_tag)
    ctag = _norm_tag(clan.get("tag"))
    our_side = clan if ctag == our_tag else opp

    members = our_side.get("members", []) or []
    missing_lines: list[str] = []
    for m in members:
        if not isinstance(m, dict):
            continue
        used = len(m.get("attacks", []) or [])
        if used < attacks_per_member:
            raw_name = str(m.get("name", "—") or "—")
            th = m.get("townhallLevel", m.get("townHallLevel", "?"))
            name_html = _maybe_mention_player(raw_name, m.get("tag"))
            missing_lines.append(f"{name_html} (TH{th}) — {used}/{attacks_per_member}")

    return "Война", missing_lines, state, end_time


def _war_sides(war: dict, clan_tag: str) -> tuple[dict, dict]:
    clan = war.get("clan", {}) or {}
    opp = war.get("opponent", {}) or {}
    our_tag = _norm_tag(clan_tag)
    ctag = _norm_tag(clan.get("tag"))
    if ctag == our_tag:
        return clan, opp
    otag = _norm_tag(opp.get("tag"))
    if otag == our_tag:
        return opp, clan
    return clan, opp


def _war_id_kv(war: dict) -> str:
    start_time = str(war.get("startTime") or "")
    opp_tag = _norm_tag(((war.get("opponent") or {}).get("tag"))).lstrip("#")
    return f"kv|{start_time}|{opp_tag}"


def _war_result_label(our: dict, opp: dict) -> str:
    our_stars = int(our.get("stars", 0) or 0)
    opp_stars = int(opp.get("stars", 0) or 0)
    if our_stars != opp_stars:
        return "Победа" if our_stars > opp_stars else "Поражение"
    our_d = float(our.get("destructionPercentage", 0.0) or 0.0)
    opp_d = float(opp.get("destructionPercentage", 0.0) or 0.0)
    if abs(our_d - opp_d) >= 0.01:
        return "Победа" if our_d > opp_d else "Поражение"
    return "Ничья"


def _format_missing_block(missing: list[str], limit: int = 20) -> str:
    if not missing:
        return "✅ Все атаки сделаны."
    block = "\n".join(f"{i}. {line}" for i, line in enumerate(missing[:limit], start=1))
    if len(missing) > limit:
        block += f"\n…и ещё <b>{len(missing) - limit}</b>"
    return "Кому ещё нужно атаковать:\n" + block


async def _broadcast_milestones_loop(bot: Bot, chat_id: int) -> None:
    """
    Auto broadcasts war/CWL milestone notifications as NEW messages:
    - start
    - ~1/3 passed
    - ~2/3 passed
    - last hour
    - end result
    """
    # Polling interval: keep it calm to avoid spam and rate limits.
    poll_seconds = 420  # 7 minutes

    active_id: str | None = None
    active_kind: str | None = None  # "КВ" | "ЛВК"
    active_war_tag: str | None = None
    sent: set[str] = set()
    idle_misses = 0
    # CWL full scan (leaguegroup + wars) is expensive. Do it редко.
    cwl_scan_cooldown_seconds = 600  # 10 минут
    cwl_next_scan_at: float = 0.0

    while True:
        try:
            await _refresh_links_cache()
            now = datetime.now(timezone.utc)

            kind = ""
            war: dict | None = None
            war_id = ""
            war_tag = None

            # Try to keep CWL checks cheap:
            # - if we already know the current CWL war tag, check it first (1 request)
            # - otherwise, do a full scan (leaguegroup + multiple wars) only every ~10 minutes
            cwl_tag: str | None = None
            cwl_war: dict | None = None
            if active_kind == "ЛВК" and active_war_tag:
                cw = await asyncio.to_thread(get_cwl_war, active_war_tag)
                if isinstance(cw, dict) and not cw.get("_error") and str(cw.get("state", "")) in {
                    "preparation",
                    "inWar",
                    "warEnded",
                }:
                    cwl_tag, cwl_war = active_war_tag, cw
                else:
                    # War tag is stale — allow scan soon
                    active_war_tag = None
                    active_kind = None

            if not cwl_tag and time.time() >= cwl_next_scan_at:
                cwl_tag, cwl_war = await asyncio.to_thread(get_current_cwl_war_for_clan)
                cwl_next_scan_at = time.time() + cwl_scan_cooldown_seconds
            if cwl_tag and isinstance(cwl_war, dict) and not cwl_war.get("_error"):
                kind = "ЛВК"
                war = cwl_war
                war_tag = str(cwl_tag)
                war_id = f"cwl|{_norm_tag(war_tag)}"
            else:
                kv = await asyncio.to_thread(get_current_war, CLAN_TAG)
                if isinstance(kv, dict) and not kv.get("_error"):
                    kind = "КВ"
                    war = kv
                    war_id = _war_id_kv(kv)

            # No active war/prep:
            # Don't immediately reset state (API can flake and cause duplicate milestone posts).
            if not kind or not isinstance(war, dict):
                idle_misses += 1
                if idle_misses >= 6:  # ~40 minutes
                    active_id = None
                    active_kind = None
                    active_war_tag = None
                    sent.clear()
                await asyncio.sleep(poll_seconds)
                continue
            idle_misses = 0

            state = str(war.get("state", "notInWar"))
            if state not in {"preparation", "inWar", "warEnded"}:
                await asyncio.sleep(poll_seconds)
                continue

            # Switch to a new war instance
            if war_id != active_id:
                active_id = war_id
                active_kind = kind
                active_war_tag = war_tag
                sent.clear()

            our, opp = _war_sides(war, CLAN_TAG)
            opp_name = _safe(opp.get("name", "соперник"))
            team_size = war.get("teamSize", "—")

            # Timing
            start_dt = _parse_coc_time(str(war.get("startTime") or ""))
            end_dt = _parse_coc_time(str(war.get("endTime") or ""))
            if not start_dt or not end_dt:
                await asyncio.sleep(poll_seconds)
                continue
            duration = max(1, int((end_dt - start_dt).total_seconds()))
            elapsed = int((now - start_dt).total_seconds())
            remaining = int((end_dt - now).total_seconds())

            # Missing list (only meaningful inWar)
            attacks_per_member = 1 if kind == "ЛВК" else int(war.get("attacksPerMember", 2) or 2)
            missing_lines: list[str] = []
            members = (our.get("members") or []) if isinstance(our.get("members"), list) else []
            for m in members:
                if not isinstance(m, dict):
                    continue
                used = len(m.get("attacks", []) or [])
                if used < attacks_per_member:
                    raw_name = str(m.get("name", "—") or "—")
                    th = m.get("townhallLevel", m.get("townHallLevel", "?"))
                    name_html = _maybe_mention_player(raw_name, m.get("tag"))
                    missing_lines.append(f"{name_html} (TH{th}) — {used}/{attacks_per_member}")

            # Milestones (dedup even if the loop restarts)
            war_sent = _broadcast_sent.get(active_id or "", {})
            now_ts = time.time()
            def _can_send(key: str, cooldown_sec: int = 6 * 3600) -> bool:
                last = float(war_sent.get(key, 0.0) or 0.0)
                return (now_ts - last) >= cooldown_sec

            if state == "inWar":
                time_left = _time_left(str(war.get("endTime") or ""))

                # Send at most ONE reminder per loop tick (so it doesn't spam in bursts)
                if "start" not in sent and _can_send("start", 12 * 3600):
                    text = (
                        f"🔥 <b>{kind} началась!</b>\n"
                        "━━━━━━━━━━━━━━━━━━━━\n\n"
                        f"Против: <b>{opp_name}</b>\n"
                        f"Формат: <b>{team_size}×{team_size}</b> • атаки: <b>{attacks_per_member}</b>\n"
                        f"До конца: <b>{_safe(time_left)}</b>\n\n"
                        f"{_format_missing_block(missing_lines)}"
                    )
                    await bot.send_message(chat_id, text, parse_mode="HTML", disable_web_page_preview=True)
                    sent.add("start")
                    war_sent["start"] = now_ts
                elif remaining <= 3600 and remaining > 0 and "last_hour" not in sent and _can_send("last_hour", 6 * 3600):
                    text = (
                        f"🚨 <b>{kind}: последний час!</b>\n"
                        "━━━━━━━━━━━━━━━━━━━━\n\n"
                        f"Осталось: <b>{_safe(time_left)}</b>\n\n"
                        f"{_format_missing_block(missing_lines)}"
                    )
                    await bot.send_message(chat_id, text, parse_mode="HTML", disable_web_page_preview=True)
                    sent.add("last_hour")
                    war_sent["last_hour"] = now_ts
                elif elapsed >= int(duration * 0.67) and "twothirds" not in sent and remaining > 3600 and _can_send("twothirds", 6 * 3600):
                    text = (
                        f"⚠️ <b>{kind}: прошло две трети</b>\n"
                        "━━━━━━━━━━━━━━━━━━━━\n\n"
                        f"До конца: <b>{_safe(time_left)}</b>\n\n"
                        f"{_format_missing_block(missing_lines)}"
                    )
                    await bot.send_message(chat_id, text, parse_mode="HTML", disable_web_page_preview=True)
                    sent.add("twothirds")
                    war_sent["twothirds"] = now_ts
                elif elapsed >= int(duration * 0.33) and "third" not in sent and remaining > 3600 and _can_send("third", 6 * 3600):
                    text = (
                        f"⏱️ <b>{kind}: прошла треть</b>\n"
                        "━━━━━━━━━━━━━━━━━━━━\n\n"
                        f"До конца: <b>{_safe(time_left)}</b>\n"
                        f"Против: <b>{opp_name}</b>\n\n"
                        f"{_format_missing_block(missing_lines)}"
                    )
                    await bot.send_message(chat_id, text, parse_mode="HTML", disable_web_page_preview=True)
                    sent.add("third")
                    war_sent["third"] = now_ts

                if active_id:
                    # store back
                    _broadcast_sent[active_id] = war_sent

            # 5) End result
            if state == "warEnded" or remaining <= 0:
                if "end" not in sent and _can_send("end", 24 * 3600):
                    # Refresh data for final numbers (especially CWL war)
                    final_war = war
                    if kind == "ЛВК" and active_war_tag:
                        fw = await asyncio.to_thread(get_cwl_war, active_war_tag)
                        if isinstance(fw, dict) and not fw.get("_error"):
                            final_war = fw
                    our_f, opp_f = _war_sides(final_war or {}, CLAN_TAG)
                    result = _war_result_label(our_f, opp_f)
                    our_stars = int(our_f.get("stars", 0) or 0)
                    opp_stars = int(opp_f.get("stars", 0) or 0)
                    our_d = float(our_f.get("destructionPercentage", 0.0) or 0.0)
                    opp_d = float(opp_f.get("destructionPercentage", 0.0) or 0.0)
                    text = (
                        f"🏁 <b>{kind} завершилась</b>\n"
                        "━━━━━━━━━━━━━━━━━━━━\n\n"
                        f"Итог: <b>{result}</b>\n"
                        f"Счёт: ⭐ <b>{our_stars}</b>:<b>{opp_stars}</b> • 💥 <b>{our_d:.2f}%</b>:<b>{opp_d:.2f}%</b>"
                    )
                    await bot.send_message(chat_id, text, parse_mode="HTML", disable_web_page_preview=True)
                    sent.add("end")
                    if active_id:
                        war_sent["end"] = now_ts
                        _broadcast_sent[active_id] = war_sent

                # After sending end, reset to avoid repeated posts
                active_id = None
                active_kind = None
                active_war_tag = None
                sent.clear()

            await asyncio.sleep(poll_seconds)
        except asyncio.CancelledError:
            raise
        except Exception as exc:
            logger.error("Broadcast loop error for chat %s: %s", chat_id, exc)
            await asyncio.sleep(poll_seconds)


async def _notify_loop(bot: Bot, chat_id: int) -> None:
    """
    Periodically sends reminders to a group chat about missing attacks in war/CWL.
    """
    poll_seconds = 300  # 5 minutes
    min_repeat_seconds = 900  # 15 minutes (avoid same message too often)
    last_fingerprint: str | None = None
    last_sent_at: float = 0.0

    while True:
        try:
            await _refresh_links_cache()
            title = None
            missing: list[str] = []
            state = ""
            end_time = ""
            context = ""

            cwl_tag, cwl_war = await asyncio.to_thread(get_current_cwl_war_for_clan)
            if cwl_tag and isinstance(cwl_war, dict) and not cwl_war.get("_error"):
                context = "ЛВК"
                title, missing, state, end_time = get_war_missing_attacks(cwl_war, CLAN_TAG)
            else:
                war = await asyncio.to_thread(get_current_war, CLAN_TAG)
                if isinstance(war, dict) and not war.get("_error"):
                    context = "КВ"
                    title, missing, state, end_time = get_war_missing_attacks(war, CLAN_TAG)

            # Build status text (always keep one message alive and updated)
            time_left = _time_left(end_time)
            state_label = "подготовка" if state == "preparation" else ("война" if state == "inWar" else "—")

            if not context or state not in {"preparation", "inWar"}:
                header = "🔔 <b>Уведомления активны</b>"
                body = (
                    "Сейчас активных войн нет.\n"
                    "<i>Я проверяю обстановку автоматически и обновляю это сообщение.</i>"
                )
                fingerprint = f"idle|{state}"
            elif state == "preparation":
                header = f"🔔 <b>{context}: идёт подготовка</b>"
                body = (
                    f"Осталось до начала: <b>{_safe(time_left)}</b>\n\n"
                    "Как только начнётся война, я буду напоминать тем, кто ещё не атаковал."
                )
                fingerprint = f"prep|{context}|{end_time}"
            elif not missing:
                header = f"🔔 <b>{context}: всё спокойно</b>"
                body = (
                    f"Сейчас: <b>{state_label}</b>\n"
                    f"Осталось: <b>{_safe(time_left)}</b>\n\n"
                    "По нашим — все атаки сделаны."
                )
                fingerprint = f"ok|{context}|{state}|{end_time}"
            else:
                missing_block = "\n".join(
                    f"{i}. {line}" for i, line in enumerate(missing[:25], start=1)
                )
                if len(missing) > 25:
                    missing_block += f"\n…и ещё <b>{len(missing) - 25}</b>"

                header = f"🔔 <b>{context}: сделайте атаки</b>"
                body = (
                    f"Сейчас: <b>{state_label}</b>\n"
                    f"Осталось: <b>{_safe(time_left)}</b>\n"
                    f"В списке: <b>{len(missing)}</b>\n"
                    "━━━━━━━━━━━━━━━━━━━━\n\n"
                    "<b>Кому ещё нужно атаковать:</b>\n"
                    f"{missing_block}"
                )
                fingerprint = f"need|{context}|{state}|{end_time}|{';'.join(missing)}"

            text = (
                f"{header}\n"
                "━━━━━━━━━━━━━━━━━━━━\n\n"
                f"{body}\n\n"
                "<i>Это сообщение обновляется само — без спама в чат.</i>"
            )

            now = time.time()
            should_send = False
            if fingerprint != last_fingerprint:
                should_send = True
            elif now - last_sent_at >= min_repeat_seconds:
                should_send = True

            if should_send:
                msg_id = _notify_message_ids.get(chat_id)
                if msg_id:
                    try:
                        await bot.edit_message_text(
                            text,
                            chat_id=chat_id,
                            message_id=msg_id,
                            parse_mode="HTML",
                            disable_web_page_preview=True,
                        )
                    except Exception:
                        msg_id = None

                if not msg_id:
                    sent = await bot.send_message(
                        chat_id, text, parse_mode="HTML", disable_web_page_preview=True
                    )
                    _notify_message_ids[chat_id] = sent.message_id

                last_fingerprint = fingerprint
                last_sent_at = now

            await asyncio.sleep(poll_seconds)
        except asyncio.CancelledError:
            raise
        except Exception as exc:
            logger.error("Notify loop error for chat %s: %s", chat_id, exc)
            await asyncio.sleep(poll_seconds)


